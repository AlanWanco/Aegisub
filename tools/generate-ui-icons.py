#!/usr/bin/env python3
"""Regenerate cross-platform PNG fallbacks from shared SVG icon paths.

Only regeneration needs librsvg's rsvg-convert executable. Normal Windows,
macOS, and Linux builds compile the checked-in PNGs as native bitmap resources.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
THEME = ROOT / "src/ui_theme.h"
OUTPUT = ROOT / "src/bitmaps/ui-generated"
MANIFEST = OUTPUT / "manifest.respack"
HEADER = ROOT / "src/ui_generated_icon_bitmaps.h"


def main() -> None:
    rsvg = shutil.which("rsvg-convert")
    if not rsvg:
        raise SystemExit("Install librsvg to regenerate shared UI icon PNG fallbacks")

    source = THEME.read_text(encoding="utf-8")
    entries = dict(re.findall(r'\{"([^"\n]+)", "(<[^"\n]+>)"\}', source))
    selected = [
        (name, paths)
        for name, paths in entries.items()
        if name.startswith("ui/")
        or name.startswith("video/tool/")
        or name in {"tool/style/manager", "tool/style/assistant", "tool/translation_assistant", "video/play/line"}
    ]
    if not selected:
        raise SystemExit("No eligible UI icon paths found in src/ui_theme.h")

    OUTPUT.mkdir(parents=True, exist_ok=True)
    manifest: list[str] = []
    groups: list[tuple[str, str, bool, bool, int]] = []
    with tempfile.TemporaryDirectory(prefix="aegisub-ui-icons-") as temp_dir:
        svg_path = Path(temp_dir) / "icon.svg"
        for name, paths in selected:
            identifier = "ui_icon_" + re.sub(r"[^a-zA-Z0-9]+", "_", name).strip("_")
            visual = name.startswith("video/tool/")
            modes = [(False, False), (False, True)]
            if visual:
                modes += [(True, False), (True, True)]
            for active, dark in modes:
                foreground = "#173D32" if active and dark else "#FFFFFF" if active else "#E4ECE9" if dark else "#253C38"
                accent = "#7BD7BC" if dark else "#126C58"
                body = ""
                if active:
                    body += f"<rect width='24' height='24' rx='4' fill='{accent}'/>"
                    body += "<g transform='translate(3 3) scale(.75)'>"
                body += paths
                if active:
                    body += "</g>"
                svg = (
                    "<svg xmlns='http://www.w3.org/2000/svg' width='48' height='48' viewBox='0 0 24 24' "
                    f"fill='none' stroke='{foreground}' stroke-width='1.7' stroke-linecap='round' stroke-linejoin='round'>"
                    f"{body}</svg>"
                )
                svg_path.write_text(svg, encoding="utf-8")
                mode = ("active_" if active else "") + ("dark" if dark else "light")
                for display, sizes, logical_size in (
                    ("small", (16, 32), 16),
                    ("regular", (24, 48), 24),
                ):
                    group = f"{identifier}_{mode}_{display}"
                    groups.append((name, group, active, dark, logical_size))
                    for pixels in sizes:
                        out = OUTPUT / f"{group}_{pixels}.png"
                        subprocess.run([rsvg, "-w", str(pixels), "-h", str(pixels), "-o", str(out), str(svg_path)], check=True)
                        manifest.append(out.name)

    MANIFEST.write_text("\n".join(manifest) + "\n", encoding="utf-8")
    declarations = [
        "// Generated by tools/generate-ui-icons.py; do not edit manually.",
        "#pragma once",
        "#include \"libresrc.h\"\n#include \"bitmap.h\"",
        "#include <string_view>",
        "namespace ui {",
        "struct GeneratedIconBitmap { std::string_view command; bool active; bool dark; const LibresrcBlob* images; size_t count; int logical_size; };",
        "inline constexpr GeneratedIconBitmap generated_icon_bitmaps[] = {",
    ]
    declarations.extend(
        f'\t{{"{name}", {str(active).lower()}, {str(dark).lower()}, {group}, sizeof({group}) / sizeof(*{group}), {logical_size}}},'
        for name, group, active, dark, logical_size in groups
    )
    declarations.extend(["};", "}"])
    HEADER.write_text("\n".join(declarations) + "\n", encoding="utf-8")
    print(f"Generated {len(manifest)} PNGs from {len(selected)} shared SVG icon paths.")


if __name__ == "__main__":
    main()
